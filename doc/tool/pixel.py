for y in range(16):
    for x in range(16):
        color_index = pixel_data[y][x]
        rgb_data[y, x] = PYXEL_PALETTE[color_index]

# 4. 画像オブジェクトを作成し、見やすいサイズに拡大して保存
img = Image.fromarray(rgb_data)
